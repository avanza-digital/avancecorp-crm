import { expect, test } from '@playwright/test'
import { entrarDemo, irACartera, irAPipeline, leadReal, loginReal, montarBackendReal, UID } from './_helpers'

test('Formulario 3 se encuentra fuera de la primera página, mantiene cifras y coincide con la ficha', async ({ page }, testInfo) => {
  const leads = Array.from({ length: 120 }, (_, i) => leadReal({
    id: `f3200000-0000-4000-8000-${String(i).padStart(12, '0')}`,
    nombre_completo: `CAMPAÑA PRUEBA ${String(i).padStart(3, '0')}`,
    telefono: `+5198400${String(i).padStart(4, '0')}`,
    vendedor_id: UID, origen: 'formulario', campania_origen: i >= 60 && i < 115 ? 'Formulario 3' : null,
    actualizado_en: new Date(Date.now() - i * 60_000).toISOString(),
  }))
  const pedidos: Record<string, unknown>[] = []
  page.on('request', request => {
    if (request.url().endsWith('/rpc/cartera_filtrada_fn')) pedidos.push(request.postDataJSON() as Record<string, unknown>)
  })
  await montarBackendReal(page, { leads })
  await loginReal(page)
  await irACartera(page)
  const tabla = page.getByRole('table', { name: 'Cartera de leads' })
  const filas = tabla.locator('tbody tr')
  const filtro = page.getByLabel('Filtrar por campaña')
  await expect(filas).toHaveCount(50)
  await expect(page.getByText('CAMPAÑA PRUEBA 060', { exact: true })).toHaveCount(0)
  await filtro.selectOption('Formulario 3')
  await expect(filas).toHaveCount(50)
  await expect(filas.first()).toContainText('CAMPAÑA PRUEBA 060')
  await expect(filas.first()).toContainText('Formulario 3')
  await expect(filas.first()).toContainText('FORMULARIO')
  await expect(page.getByRole('button', { name: /^Total leads 55/ })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('cartera-formulario3.png') })
  await page.getByRole('button', { name: /cargar más leads/i }).click()
  await expect(filas).toHaveCount(55)
  await expect(filas.last()).toContainText('CAMPAÑA PRUEBA 114')
  const consultasCampania = pedidos.filter(p => p.p_campania_origen === 'Formulario 3')
  expect(consultasCampania).toHaveLength(2)
  expect(consultasCampania[0]).not.toHaveProperty('p_antes_id')
  expect(consultasCampania[1]?.p_antes_id).toBe(leads[109]?.id)
  await filas.first().focus()
  await page.keyboard.press('Enter')
  const ficha = page.getByRole('dialog', { name: 'CAMPAÑA PRUEBA 060', exact: true })
  await expect(ficha.getByTitle('Campaña de origen: Formulario 3')).toBeVisible()
  await expect(ficha).toContainText('FORMULARIO')
  await expect(ficha.getByRole('textbox', { name: /campaña/i })).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('ficha-formulario3.png') })
  await ficha.getByRole('button', { name: 'Cerrar ficha', exact: true }).click()
  await expect(filtro).toHaveValue('Formulario 3')
  await page.reload()
  await irACartera(page)
  await expect(filtro).toHaveValue('Formulario 3')
  await expect(filas).toHaveCount(50)
  await expect(filas.first()).toContainText('CAMPAÑA PRUEBA 060')
  await expect(page.getByRole('button', { name: /^Total leads 55/ })).toBeVisible()
  await page.getByRole('button', { name: 'Limpiar filtros' }).click()
  await expect(filtro).toHaveValue('todas')
  await expect(filas.first()).toContainText('CAMPAÑA PRUEBA 000')
  await expect(filas.first().getByTitle(/Campaña de origen/)).toHaveCount(0)

  // El Pipeline lee sus propias páginas: también debe conservar el dato al
  // cargar una tarjeta fuera de las primeras 50 y abrir su ficha por teclado.
  await irAPipeline(page)
  const tarjeta = page.locator(`[data-foco-clave="lead-${leads[60]!.id}"]`)
  const historica = page.locator(`[data-foco-clave="lead-${leads[0]!.id}"]`)
  await expect(historica).toBeVisible()
  await expect(historica.getByTitle(/Campaña de origen/)).toHaveCount(0)
  await expect(tarjeta).toHaveCount(0)
  await page.getByRole('button', { name: 'Cargar más leads de Nuevo', exact: true }).click()
  await tarjeta.scrollIntoViewIfNeeded()
  await expect(tarjeta.getByTitle('Campaña de origen: Formulario 3')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('pipeline-formulario3.png') })
  await tarjeta.focus()
  await page.keyboard.press('Enter')
  await expect(ficha.getByTitle('Campaña de origen: Formulario 3')).toBeVisible()
  await expect(ficha).toContainText('FORMULARIO')
})

test('cartera histórica sin campañas conserva sus leads y da cero al filtrar Formulario 3', async ({ page }) => {
  await montarBackendReal(page, { leads: [leadReal({ vendedor_id: UID, origen: 'formulario', nota: 'Reingreso de Formulario 3' })] })
  await loginReal(page)
  await irACartera(page)
  const fila = page.getByRole('row', { name: /CLIENTE REAL UNO/ })
  await expect(fila).toBeVisible()
  await expect(fila.getByTitle(/Campaña de origen/)).toHaveCount(0)
  await page.getByLabel('Filtrar por campaña').selectOption('Formulario 3')
  await expect(fila).toHaveCount(0)
  await expect(page.getByText('Sin resultados', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /^Total leads 0/ })).toBeVisible()
  await page.getByRole('button', { name: 'Limpiar filtros' }).click()
  await expect(fila).toBeVisible()
})

test('demo muestra campaña en cartera y ficha, con filtro usable en pantalla estrecha', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await entrarDemo(page, 'Analista')
  await irACartera(page)
  const filtro = page.getByLabel('Filtrar por campaña')
  await filtro.selectOption('Formulario 3')
  const fila = page.getByRole('row', { name: /PATRICIA FERNÁNDEZ/ })
  await expect(fila).toContainText('Formulario 3')
  const limites = await filtro.boundingBox()
  expect(limites).not.toBeNull()
  expect(limites!.x).toBeGreaterThanOrEqual(0)
  expect(limites!.x + limites!.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: testInfo.outputPath('campania-movil.png') })
  await fila.click()
  await expect(page.getByRole('dialog').getByTitle('Campaña de origen: Formulario 3')).toBeVisible()
})
